export function filterCuratedSongs(query: string, category: MoodCategory = 'All'): Track[] {
  const normalizedQuery = query.trim().toLowerCase();
  return CURATED_INDIAN_SONGS.filter((song) => {
    const matchesCategory = category === 'All' || song.category === category;
    if (!matchesCategory) return false;
    if (!normalizedQuery) return true;
    return (
      song.title.toLowerCase().includes(normalizedQuery) ||
      song.channel.toLowerCase().includes(normalizedQuery) ||
      (song.category && song.category.toLowerCase().includes(normalizedQuery)) ||
      (song.language && song.language.toLowerCase().includes(normalizedQuery))
    );
  });
}
